function check_db_avail() {
    PGPASSWORD=$(cat tests/secrets/ebs_db_pw) \
    pg_isready --quiet \
               --dbname elnbuildsync \
               --username elnbuildsync \
               --host localhost \
               --port 5432
    db_ready=$?
}

function closedb() {
    echo "Terminating non-persistent database"
    ${CONTAINER_ENGINE} stop temp_postgres
}

# Prepare the container network
${CONTAINER_ENGINE} network create --ignore ebs_local_test

# Check if there's already a database running so we don't start another one
check_db_avail > /dev/null 2>&1

if [ $db_ready -ne 0 ]; then
    # Start a database for testing
    echo -n "Starting up database container "

	if [ "$_arg_persistent_db" == "on" ]; then
	    echo "using persistent database"
		mkdir -p ${_arg_persistent_db_path}
		PERSISTENT_DB_ARG="--volume ${_arg_persistent_db_path}:/var/lib/postgresql/data:Z"
	else
		echo "using non-persistent database"
		PERSISTENT_DB_ARG=""
	fi
    ${CONTAINER_ENGINE} pull docker.io/postgres:$POSTGRES_VERSION
    ${CONTAINER_ENGINE} run --rm --detach \
		--publish 5432:5432 \
	    --network ebs_local_test \
        --volume ${SCRIPT_DIR}/secrets:/run/secrets:Z \
        --name temp_postgres \
        --env POSTGRES_PASSWORD_FILE=/run/secrets/ebs_db_pw \
        --env POSTGRES_USER=elnbuildsync \
        docker.io/postgres:$POSTGRES_VERSION
    trap closedb EXIT

    echo Started database container, waiting for it to complete initialization

    # Wait for the DB to start up
    db_ready=-1
    while [ $db_ready -ne 0 ]; do
        sleep 0.1
        check_db_avail
    done
fi

