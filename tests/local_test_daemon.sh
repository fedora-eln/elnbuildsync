parse_commandline()
{
	_positionals_count=0
	local _key
	while test $# -gt 0
	do
		_key="$1"
		if test "$_key" = '--'
		then
			shift
			test $# -gt 0 || break
			_positionals+=("$@")
			_positionals_count=$((_positionals_count + $#))
			shift $(($# - 1))
			_last_positional="$1"
			break
		fi
		case "$_key" in
			--log-level)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_log_level="$2"
				shift
				;;
			--log-level=*)
				_arg_log_level="${_key##--log-level=}"
				;;
			--db-pw-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_db_pw_file="$2"
				shift
				;;
			--db-pw-file=*)
				_arg_db_pw_file="${_key##--db-pw-file=}"
				;;
			--smtp-pw-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_smtp_pw_file="$2"
				shift
				;;
			--smtp-pw-file=*)
				_arg_smtp_pw_file="${_key##--smtp-pw-file=}"
				;;
			--lull-time)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_lull_time="$2"
				shift
				;;
			--lull-time=*)
				_arg_lull_time="${_key##--lull-time=}"
				;;
			--config-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_config_file="$2"
				shift
				;;
			--config-file=*)
				_arg_config_file="${_key##--config-file=}"
				;;
			--environment)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_environment="$2"
				shift
				;;
			--environment=*)
				_arg_environment="${_key##--environment=}"
				;;
			--no-persistent-db|--persistent-db)
				_arg_persistent_db="on"
				test "${1:0:5}" = "--no-" && _arg_persistent_db="off"
				;;
			--persistent-db-path)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_persistent_db_path="$2"
				shift
				;;
			--persistent-db-path=*)
				_arg_persistent_db_path="${_key##--persistent-db-path=}"
				;;
			--no-build-container|--build-container)
				_arg_build_container="on"
				test "${1:0:5}" = "--no-" && _arg_build_container="off"
				;;
			-h|--help)
				print_help
				exit 0
				;;
			-h*)
				print_help
				exit 0
				;;
			*)
				_last_positional="$1"
				_positionals+=("$_last_positional")
				_positionals_count=$((_positionals_count + 1))
				;;
		esac
		shift
	done
}


assign_positional_args()
{
	local _positional_name _shift_for=$1
	_positional_names=""
